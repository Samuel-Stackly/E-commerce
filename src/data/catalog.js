export const categories = [...new Set(allProducts.map((p) => p.category))]
export const brands = [...new Set(allProducts.map((p) => p.brand))]

export function getProductById(id) {
  return allProducts.find((p) => String(p.id) === String(id))
}

export function getRelatedProducts(product, limit = 5) {
  if (!product) return []
  return allProducts
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, limit)
}
